/** Латиница — запасной вариант, если имя введено не кириллицей. */
const LATIN_VOWELS = new Set(["A", "E", "I", "O", "U"]);
const LATIN_ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";

function latinValue(letter: string): number {
  const index = LATIN_ALPHABET.indexOf(letter);
  if (index === -1) return 0;
  return (index % 9) + 1;
}

/**
 * Сворачивает число до однозначного.
 * Мастер-числа 11, 22, 33 останавливают свёртку, если allowMaster = true.
 */
export function reduceNumber(value: number, allowMaster = true): NumerologyNumber {
  let current = Math.abs(Math.trunc(value));

  if (current === 0) return 9;

  while (current > 9) {
    if (allowMaster && MASTER_NUMBERS.includes(current)) {
      return current as NumerologyNumber;
    }
    current = String(current)
      .split("")
      .reduce((sum, digit) => sum + Number(digit), 0);
  }

  return current as NumerologyNumber;
}

export function isMasterNumber(value: number): boolean {
  return MASTER_NUMBERS.includes(value);
}

/**
 * Число судьбы: сумма всех цифр даты рождения (ДД + ММ + ГГГГ).
 * Пример: 15.04.1990 -> 1+5+0+4+1+9+9+0 = 29 -> 2+9 = 11 (мастер-число).
 */
export function calculateDestinyNumber(birthDate: string): NumerologyNumber {
  const digits = birthDate.replace(/\D/g, "");
  if (!digits) return 9;

  const sum = digits.split("").reduce((total, digit) => total + Number(digit), 0);
  return reduceNumber(sum, true);
}

function normalizeName(name: string): string {
  return name.toUpperCase().replace(/Ё/g, "Ё");
}

/** Число души: сумма гласных имени. */
export function calculateSoulNumber(name: string): NumerologyNumber {
  const letters = normalizeName(name);
  let sum = 0;

  for (const letter of letters) {
    if (letter in RU_VOWELS) {
      sum += RU_VOWELS[letter];
    } else if (LATIN_VOWELS.has(letter)) {
      sum += latinValue(letter);
    }
  }

  return reduceNumber(sum, true);
}

/** Число личности: сумма согласных имени по таблице Пифагора. */
export function calculatePersonalityNumber(name: string): NumerologyNumber {
  const letters = normalizeName(name);
  let sum = 0;

  for (const letter of letters) {
    if (letter in RU_CONSONANTS) {
      sum += RU_CONSONANTS[letter];
    } else if (!LATIN_VOWELS.has(letter) && LATIN_ALPHABET.includes(letter)) {
      sum += latinValue(letter);
    }
  }

  return reduceNumber(sum, true);
}

/** Число денег: число судьбы + число души, свёрнутое до однозначного. */
export function calculateMoneyNumber(
  destinyNumber: number,
  soulNumber: number
): NumerologyNumber {
  return reduceNumber(destinyNumber + soulNumber, false);
}

export function calculateNumerology(name: string, birthDate: string): NumerologyResult {
  const destinyNumber = calculateDestinyNumber(birthDate);
  const soulNumber = calculateSoulNumber(name);
  const personalityNumber = calculatePersonalityNumber(name);
  const moneyNumber = calculateMoneyNumber(destinyNumber, soulNumber);

  return { destinyNumber, soulNumber, personalityNumber, moneyNumber };
}

