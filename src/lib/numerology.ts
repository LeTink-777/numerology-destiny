/** Первые две фразы описания — для короткой карточки числа души. */
export function shortDescription(text: string, sentences = 2): string {
  const parts = text.match(/[^.!?]+[.!?]+/g);
  if (!parts) return text;
  return parts
    .slice(0, sentences)
    .map((part) => part.trim())
    .join(" ");
}

export function formatBirthDate(isoDate: string): string {
  if (!isoDate) return "";
  const [year, month, day] = isoDate.split("-");
  if (!year || !month || !day) return isoDate;
  return `${day}.${month}.${year}`;
}
